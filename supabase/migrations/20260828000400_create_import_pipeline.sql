-- STEP 4: 서버 검증 후 승인된 파일만 RAW에 적재하는 batch 기반 파이프라인.
-- RAW 대상은 migration 시점에 강제하지 않는다. 실제 적재 시점에만 안전하게 검증한다.

create schema if not exists core;

create table if not exists core.upload_batch (
  batch_id uuid primary key default gen_random_uuid(),
  file_name text not null,
  import_type text not null check (import_type in ('usage_history', 'inventory', 'item_master', 'supplier_master', 'purchase_order', 'goods_receipt', 'sales_order', 'business_event')),
  import_mode text not null check (import_mode in ('append', 'upsert', 'replace')),
  total_rows integer not null default 0 check (total_rows >= 0), success_rows integer not null default 0 check (success_rows >= 0),
  warning_rows integer not null default 0 check (warning_rows >= 0), error_rows integer not null default 0 check (error_rows >= 0),
  status text not null default 'PARSED' check (status in ('PARSED', 'VALIDATED', 'IMPORTED', 'ROLLED_BACK', 'FAILED')),
  rollback_supported boolean generated always as (import_mode <> 'replace') stored,
  uploaded_by uuid not null references auth.users(id), uploaded_at timestamptz not null default now(),
  imported_by uuid references auth.users(id), imported_at timestamptz, rolled_back_by uuid references auth.users(id), rolled_back_at timestamptz,
  failure_code text, failure_message text,
  check (success_rows + warning_rows + error_rows <= total_rows)
);

create table if not exists core.import_staging (
  staging_id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  row_number integer not null check (row_number > 0), original_data jsonb not null, normalized_data jsonb,
  source_record_id text not null, mapping_confirmed boolean not null default false,
  validation_status text check (validation_status in ('SUCCESS', 'WARNING', 'ERROR')), validated_at timestamptz,
  created_at timestamptz not null default now(), unique (batch_id, row_number)
);

create table if not exists core.column_mapping (
  mapping_id uuid primary key default gen_random_uuid(),
  import_type text not null check (import_type in ('usage_history', 'inventory', 'item_master', 'supplier_master', 'purchase_order', 'goods_receipt', 'sales_order', 'business_event')),
  source_header text not null, standard_field text not null, raw_column text not null,
  created_by uuid not null references auth.users(id), created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique (import_type, source_header)
);

create table if not exists core.validation_error (
  validation_error_id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade, row_number integer not null check (row_number > 0),
  field_name text, error_code text not null, error_message text not null,
  severity text not null check (severity in ('WARNING', 'ERROR')), original_value text, created_at timestamptz not null default now()
);

create table if not exists core.import_rollback_snapshot (
  snapshot_id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade, import_type text not null, raw_table text not null,
  source_record_id text not null, raw_record jsonb not null, captured_at timestamptz not null default now(), restored_at timestamptz,
  unique (batch_id, raw_table, source_record_id)
);

create table if not exists core.forecast_data_change (
  change_id bigint generated by default as identity primary key,
  batch_id uuid not null unique references core.upload_batch(batch_id) on delete cascade,
  import_type text not null check (import_type in ('usage_history', 'sales_order', 'business_event')),
  changed_at timestamptz not null default now(), rolled_back_at timestamptz
);

